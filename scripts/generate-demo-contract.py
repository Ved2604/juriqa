def build_pdf(path: str, v2: bool):
    ss = getSampleStyleSheet()
    title = ParagraphStyle("t", parent=ss["Title"], fontSize=16)
    h = ParagraphStyle("h", parent=ss["Heading2"], fontSize=11.5, spaceBefore=10)
    p = ParagraphStyle("p", parent=ss["BodyText"], fontSize=10, leading=14, spaceAfter=7, alignment=4)
    label = "Version 2 - revised draft" if v2 else "Version 1"

    def deco(c, d):
        c.saveState()
        c.setFont("Helvetica", 8)
        c.drawString(72, A4[1] - 40, f"SOFTWARE SERVICES AGREEMENT - {label.upper()} - CONFIDENTIAL")
        c.drawCentredString(A4[0] / 2, 30, f"Page {d.page}")
        c.restoreState()

    story = [Paragraph("SOFTWARE SERVICES AGREEMENT", title), Spacer(1, 6)]
    story += [Paragraph(t, p) for t in PREAMBLE]
    story.append(Paragraph("IT IS AGREED as follows:", p))
    for n, (heading, clauses) in enumerate(sections(v2), 1):
        story.append(Paragraph(f"{n}. {heading}", h))
        for k, text in enumerate(clauses, 1):
            story.append(Paragraph(f"{n}.{k} {text}", p))
    story.append(PageBreak())
    for heading, items in SCHEDULES:
        story.append(Paragraph(heading, h))
        for k, text in enumerate(items, 1):
            story.append(Paragraph(f"{k}. {text}", p))
    story.append(Spacer(1, 18))
    story.append(Paragraph(f"Signed for and on behalf of {CUSTOMER} by its authorised signatory.", p))
    story.append(Paragraph(f"Signed for and on behalf of {SUPPLIER} by its authorised signatory.", p))
    SimpleDocTemplate(path, pagesize=A4, topMargin=60, bottomMargin=55).build(story, onFirstPage=deco, onLaterPages=deco)


def build_docx(path: str):
    d = docx.Document()
    d.add_heading("SOFTWARE SERVICES AGREEMENT", 0)
    for t in PREAMBLE:
        d.add_paragraph(t)
    d.add_paragraph("IT IS AGREED as follows:")
    for n, (heading, clauses) in enumerate(sections(False), 1):
        d.add_heading(f"{n}. {heading}", 2)
        for k, text in enumerate(clauses, 1):
            para = d.add_paragraph()
            para.add_run(f"{n}.{k} ").bold = True
            para.add_run(text)
    for heading, items in SCHEDULES:
        d.add_heading(heading, 2)
        for k, text in enumerate(items, 1):
            d.add_paragraph(f"{k}. {text}")
    d.add_paragraph(f"Signed for and on behalf of {CUSTOMER} by its authorised signatory.")
    d.add_paragraph(f"Signed for and on behalf of {SUPPLIER} by its authorised signatory.")
    d.save(path)


